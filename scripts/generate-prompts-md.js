// Renders PROMPTS.md from src/prompts.js so the copy-paste blocks for clients without
// native MCP prompt support can never drift from the registered prompts.
// Run: npm run generate:prompts-md
const fs = require('fs');
const path = require('path');
const { registerAllPrompts } = require('../src/prompts');

const prompts = {};
registerAllPrompts({ registerPrompt: (name, def, cb) => { prompts[name] = { def, cb }; } });

const placeholder = { board: '<BOARD_PUBLIC_ID>', card: '<CARD_ID>', aging_days: undefined, hours: undefined };
const sections = Object.entries(prompts).map(([name, { def, cb }]) => {
    const args = Object.keys(def.argsSchema).map(k => `\`${k}\``).join(', ');
    const text = cb(placeholder).messages[0].content.text;
    return [`## ${def.title}`, '', def.description, '', `Arguments: ${args}`, '', '```', text, '```'].join('\n');
});

const doc = [
    '# Prompts',
    '',
    '<!-- Generated by scripts/generate-prompts-md.js — run `npm run generate:prompts-md`, never edit by hand. -->',
    '',
    'The server ships three user-invocable prompts. In **Claude Code** they appear as slash commands',
    '(`/mcp__kanbanzone__board_review` and friends); in **Claude Desktop** they are items in the prompt',
    'picker (the + menu). Clients without MCP prompt support (ChatGPT, Perplexity, and others vary):',
    'copy the block you need below, replace the `<PLACEHOLDERS>`, and paste it into the chat — the',
    'text is identical to what the native prompts send.',
    '',
    sections.join('\n\n'),
    '',
].join('\n');

fs.writeFileSync(path.join(__dirname, '..', 'PROMPTS.md'), doc);
console.log(`PROMPTS.md written (${doc.length} chars, ${Object.keys(prompts).length} prompts).`);
